def _fmt_dur(d):
    if all(x == 0 for x in d):
        return 'static'
    if len(set(d)) == 1:
        return f'{d[0]:g} s each'
    return ' / '.join(f'{x:g}' for x in d) + ' s'


def write(sheets, out_dir, sections=None):
    """`sections` maps a sheet name to a block of text written just before it."""
    lines = [INTRO]
    for name, s in sheets.items():
        if sections and name in sections:
            lines.append(sections[name])
        lines.append(f"### {name}.png ({s['fw']}x{s['fh']} frames)\n")
        lines.append(s['about'] + '\n')
        lines.append('| Row | Animation | Frames | Timing | Loops | Notes |')
        lines.append('|---|---|---|---|---|---|')
        for anim in s['order']:
            a = s['anims'][anim]
            loop = 'yes' if a['loop'] and any(a['dur']) else 'no'
            if not any(a['dur']):
                loop = ''
            note = a['note'].replace('|', '/')
            lines.append(f"| {a['row']} | {anim} | {a['frames']} | {_fmt_dur(a['dur'])} | {loop} | {note} |")
        lines.append('')
    with open(os.path.join(out_dir, 'README.md'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(lines))
