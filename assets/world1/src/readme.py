INTRO = """# World 1, World 2 and World 3 art

Sprite sheets for every World 1 tile, trap, enemy, pickup and effect, plus the
Gate transmitter backdrop. The World 2 (The Switchyard), atmosphere, village
and World 3 (The Aerials) sheets come after them, in the same folder and
pipeline. Generated by `src/make_sheets.py` (Python + Pillow).

## Rules the art follows

- Four greys only: `#0b0b0b` `#3a3a3a` `#8a8a8a` `#f2f2f2`, plus transparency.
  The generator refuses to write a pixel of any other colour.
- 16 px tiles, drawn for a 480x270 canvas with nearest-neighbour scaling.
- White means alive or important: lit lips you can stand on, pickups, the one
  lamp on a dead panel. Backdrops stay dark.
- Danger is shown by shape and motion: teeth, cracks, jitter and blink frames.
  Every enemy and trap has a 2 to 3 frame warning ("tell") before it acts.
- Dither uses the same 4x4 Bayer matrix as `scripts/draw_util.gd`. Every frame
  is 16 px aligned, so the pattern lines up with world coordinates and never
  swims when the camera scrolls.
- The Spark is not in these sheets. It stays the coded white block from
  `scripts/spark_visual.gd`. Effects around it (dash ghosts, dust, CHARGE glow)
  are here or in `scripts/world1/juice.gd`.

## How to read a sheet

Each row is one animation, or one set of static variants. Frames run left to
right. `sheets.json` and `scripts/world1/sheet_data.gd` hold the same data:
frame size, the row of each animation, its frame count, the time each frame is
shown (seconds) and whether it loops. A time of 0 means a static frame.

All sprites face left. Mirror them for right. Unless a note says otherwise,
draw a sprite with its top-left on the tile's top-left. Bigger sprites say
where they anchor in their note.

## Regenerate, view, capture

- Regenerate: `python assets/world1/src/make_sheets.py` from the project root.
- View: open `scenes/world1_showcase.tscn` and press F6. Left and right change
  page. F toggles the screen shader, S shakes the screen, T is slow motion,
  P pauses, Space restarts the loops, Up and Down change level on the last page.
- Capture: `"E:/Godot games/Godot_v4.7.2-stable_win64.exe" --path . --resolution 960x540 --script res://scripts/world1/showcase_capture.gd`
  writes PNGs to `test-user/world1-art/`.

## Code that goes with the art

- `scripts/world1/sheets.gd` loads every sheet and draws a frame by sheet and
  animation name, with the manifest's timing. Mirrored frames use a pre-flipped
  copy of the sheet.
- `scripts/world1/juice.gd` holds the effects as plain functions of time:
  screen shake, hit-stop, particles, dust, grit, speed lines, glints, dash
  ghosts and the Spark itself. No random numbers, so every effect replays the
  same way and can be captured frame by frame.
- `shaders/world1/signal_crt.gdshader` is the optional screen pass: a soft
  bloom on white only, scanlines on the game's own pixel rows, dark edges.
- `scripts/world1/level_view.gd` draws the real `levels/world1/*.txt` maps with
  these tiles. It reads the same legend and `[objects]` timings as
  `tools/levels/levelkit.py`.

## Sheets
"""


